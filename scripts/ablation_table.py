"""Internal-validation ablation table (reports/ablations.md and paper/table_ablations.tex).

Every row comes from experiments/<name>/metrics.json (F1 with thresholds tuned on internal
validation, and at a fixed 0.5) and experiments/<name>/measure_val.json (official-loop cost on
internal validation; the score column projects that cost to public-test size).
Usage: python scripts/ablation_table.py
"""

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
from leaderboard import test_over_val  # noqa: E402

from aegis.evaluation.official import submission_score  # noqa: E402

ROWS = [  # (group, label, experiments [seeds])
    ("Depth (no KD)", "1 layer", ["student_unix_L1"]),
    ("Depth (no KD)", "2 layers", ["student_unix_L2"]),
    ("Depth (no KD)", "3 layers", ["student_unix_L3", "student_unix_L3_s43", "student_unix_L3_s44"]),
    ("Depth (no KD)", "4 layers", ["student_unix_L4"]),
    ("Depth (no KD)", "6 layers", ["student_unix_L6"]),
    ("Depth (no KD)", "12 layers (teacher)", ["teacher_unixcoder"]),
    ("Distillation", "2 layers + KD", ["kd_teacher_L2"]),
    ("Distillation", "3 layers + KD (AEGIS)", ["kd_teacher_L3", "kd_teacher_L3_s43", "kd_teacher_L3_s44"]),
    ("Distillation", "4 layers + KD", ["kd_teacher_L4"]),
    ("Variants of AEGIS", "pretrained init (2 layers)", ["kd_pre_L2"]),
    ("Variants of AEGIS", "6 epochs", ["kd_teacher_L3_e6"]),
    ("Variants of AEGIS", "raw input (no normalization)", ["kd_teacher_L3_raw"]),
    ("Reference", "4x256 from scratch", ["student_scratch_4x256"]),
]


def stats(names: list[str]) -> dict | None:
    recs = []
    for n in names:
        mf, mv = ROOT / f"experiments/{n}/metrics.json", ROOT / f"experiments/{n}/measure_val.json"
        if not (mf.exists() and mv.exists()):
            return None
        b = json.loads(mf.read_text())["best"]
        r = json.loads(mv.read_text())
        k = test_over_val(r)
        recs.append(dict(vuln=b["val_tuned"]["f1_vuln"], mat=b["val_tuned"]["f1_mat"], mean=b["val_mean_f1_tuned"],
                         mean05=b["val_at_0.5"]["mean_f1"], gflops=r["avg_flops"], runtime=r["avg_runtime"],
                         proj=submission_score(b["val_mean_f1_tuned"], r["avg_runtime"] * k, r["avg_flops"] * k)))
    out = {key: float(np.mean([r[key] for r in recs])) for key in recs[0]}
    out["mean_sd"] = float(np.std([r["mean"] for r in recs], ddof=1)) if len(recs) > 1 else None
    out["n"] = len(recs)
    return out


def main() -> None:
    md = ["# Ablations on internal validation (auto-generated by scripts/ablation_table.py)", "",
          "F1 with per-task thresholds tuned on internal validation; `F1@0.5` uses the fixed 0.5 threshold. "
          "Cost: official measurement loop on internal validation (21,243 functions). `Proj. score`: official "
          "formula with cost scaled to the public-test size.", "",
          "| Group | Model | seeds | Weakness F1 | MAT F1 | Mean F1 | Mean F1@0.5 | GFLOPs (val) | Runtime s (val) | Proj. score |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    tex = [r"\begin{table}[t]", r"\centering", r"\caption{Internal-validation ablations. F1 uses validation-tuned thresholds; "
           r"cost is measured with the official loop on internal validation; the score projects that cost to the public-test size. "
           r"Rows with $\pm$ average three seeds.}", r"\label{tab:ablations}", r"\setlength{\tabcolsep}{3pt}", r"\footnotesize",
           r"\begin{tabular}{lcccrc}", r"\toprule", r"Model & Weak.\ F1 & MAT F1 & Mean F1 & GFLOPs & Score \\", r"\midrule"]
    group = None
    for g, label, names in ROWS:
        s = stats(names)
        if s is None:
            continue
        sd = f" ± {s['mean_sd']:.4f}" if s["mean_sd"] is not None else ""
        md.append(f"| {g} | {label} | {s['n']} | {s['vuln']:.4f} | {s['mat']:.4f} | {s['mean']:.4f}{sd} | {s['mean05']:.4f} | "
                  f"{s['gflops']:,.0f} | {s['runtime']:.2f} | {s['proj']:.4f} |")
        if g != group and group is not None:
            tex.append(r"\midrule")
        group = g
        sdt = f"$\\pm${s['mean_sd']:.4f}" if s["mean_sd"] is not None else ""
        tex.append(f"{label} & {s['vuln']:.3f} & {s['mat']:.3f} & {s['mean']:.3f}{sdt} & {s['gflops'] / 1e3:.0f}k & {s['proj']:.3f} \\\\")
    tex += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (ROOT / "reports" / "ablations.md").write_text("\n".join(md) + "\n")
    (ROOT / "paper" / "table_ablations.tex").write_text("\n".join(tex) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
