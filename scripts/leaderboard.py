"""Aggregate experiment results into reports/leaderboard.{csv,md}.

val_* columns come from experiments/<name>/metrics.json (internal validation split).
Measurement rows come from experiments/<name>/measure_<split>.json (official measurement loop).
Runtime/GFLOPs are split totals, so `score` is only comparable between rows of the same split
(internal val has 21,243 functions, public test 30,655). Rows from different hardware/power modes
are flagged via the `hardware` column.
"""

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from aegis.evaluation.official import submission_score  # noqa: E402
from aegis.paths import EXPERIMENTS_DIR, REPORTS_DIR  # noqa: E402

BASELINE_SCORE_OFFICIAL = 0.7286  # formula applied to the organizers' printed T4 values
# Real tokens in the public test split for UniXcoder + single-line input (reports/token_budget.csv).
TEST_TOKENS_UNIXCODER_SINGLE_LINE = 4_702_705


def test_over_val(r: dict) -> float:
    """Cost scales with processed tokens: ratio of public-test tokens to this run's val tokens.
    Valid for UniXcoder-tokenized single-line inputs (all AEGIS students)."""
    return TEST_TOKENS_UNIXCODER_SINGLE_LINE / (r["n_samples"] * r["extra"]["mean_input_tokens"])


def main() -> None:
    rows = []
    for d in sorted(EXPERIMENTS_DIR.iterdir()):
        if not d.is_dir() or d.name.startswith("smoke"):
            continue
        m = json.loads((d / "metrics.json").read_text()) if (d / "metrics.json").exists() else {}
        best = m.get("best", {})
        base = {
            "experiment": d.name,
            "val_mean_f1": best.get("val_mean_f1_tuned", (m.get("val_tuned") or {}).get("mean_f1")),
            "val_f1_vuln": (best.get("val_tuned") or m.get("val_tuned") or {}).get("f1_vuln"),
            "val_f1_mat": (best.get("val_tuned") or m.get("val_tuned") or {}).get("f1_mat"),
            "params_non_emb_M": round(m["params"]["non_embedding"] / 1e6, 2) if "params" in m else None,
            "train_time_min": round(m["train_time_s"] / 60, 1) if "train_time_s" in m else None,
        }
        measures = sorted(d.glob("measure_*.json"))
        if not measures:
            rows.append(base)
        for f in measures:
            r = json.loads(f.read_text())
            env = r.get("extra", {}).get("env", {})
            rows.append({
                **base, "measurement": f.stem, "split": r.get("extra", {}).get("split"),
                "n": r.get("n_samples"),
                "f1_vuln": r["scores"][0]["f1"], "f1_mat": r["scores"][1]["f1"],
                "mean_f1": r["avg_f1"], "runtime_s": r["avg_runtime"], "gflops": r["avg_flops"],
                "analytic_total_gflops": r.get("extra", {}).get("analytic", {}).get("total_gflops"),
                "score": r["score"],
                # Cost scales with processed tokens; project val measurements to the public-test size.
                "projected_test_score": submission_score(
                    r["avg_f1"], r["avg_runtime"] * test_over_val(r), r["avg_flops"] * test_over_val(r))
                if r.get("extra", {}).get("split") == "val" else r["score"],
                "delta_vs_official_baseline": r["score"] - BASELINE_SCORE_OFFICIAL,
                "batching": r.get("batching"), "hardware": f"{env.get('gpu', '?')} | {env.get('gpu_power_state', '?')}",
            })
    df = pd.DataFrame(rows)
    REPORTS_DIR.mkdir(exist_ok=True)
    df.to_csv(REPORTS_DIR / "leaderboard.csv", index=False)
    (REPORTS_DIR / "leaderboard.md").write_text(
        "# Local leaderboard (auto-generated by scripts/leaderboard.py)\n\n"
        "Runtime is hardware-dependent: rows are directly comparable only with the same `hardware` entry. "
        "The official baseline score 0.7286 was obtained on a Colab T4.\n\n"
        + df.to_markdown(index=False, floatfmt=".4f") + "\n")
    print(df.to_string())


if __name__ == "__main__":
    main()
